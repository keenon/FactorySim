//! `fsim-sales`: Markets and demand vertical slice.
//! Starts with the Online Prototyping Marketplace (Xometry-style acceptance policy, no certs or
//! salespeople needed) and includes unlockable regulated/commercial markets (Aerospace AS9100,
//! Medical ISO 13485, Contract Manufacturing, Amazon Consumer Goods), certifications, and
//! late/out-of-tolerance penalties.

pub mod reference;

use fsim_core::{Money, SimTime, StreamRng};
use serde::{Deserialize, Serialize};

/// Definition of a market segment on the Markets tab.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MarketDefinition {
    pub market_id: String,
    pub name: String,
    pub description: String,
    pub required_certs: Vec<String>,
    pub requires_cmm: bool,
    pub requires_salesperson: bool,
    pub base_order_interval_hours: u32,
    pub reference_payout_per_part: Money,
}

/// Player-configurable bidding / acceptance policy for a market on a given plant.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct MarketBiddingPolicy {
    pub market_id: String,
    pub enabled: bool,
    pub min_payout_per_hour: Money,
    pub price_multiplier_pct: u32, // 100 = middle-of-the-road reference price
    pub promised_lead_days: u32,
    pub max_active_backlog: u32,
    pub allow_aluminum: bool,
    pub allow_steel: bool,
    pub allow_molded_plastic: bool,
}

impl MarketBiddingPolicy {
    pub fn sensible_default(market_id: &str, enabled: bool) -> Self {
        Self {
            market_id: market_id.to_string(),
            enabled,
            min_payout_per_hour: Money::from_dollars(95),
            price_multiplier_pct: 100,
            promised_lead_days: 7,
            max_active_backlog: 12,
            allow_aluminum: true,
            allow_steel: true,
            allow_molded_plastic: true,
        }
    }
}

/// An active or completed customer order generated by a market stream.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct CustomerOrder {
    pub customer_order_id: String,
    pub plant_id: String,
    pub market_id: String,
    pub part_name: String,
    pub material_sku: String, // "blank-alu", "raw-bar-alu", "resin-pellet"
    pub requires_sawing: bool,
    pub requires_inspection: bool,
    pub quantity: u32,
    pub payout: Money,
    pub created_at_ms: i64,
    pub due_at_ms: i64,
    pub status: String, // "active", "shipped_on_time", "shipped_late", "rejected_out_of_spec"
}

