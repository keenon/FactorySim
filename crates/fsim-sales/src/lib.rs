/// Stochastically samples a new `CustomerOrder` if the market policy is enabled and wins the bid.
pub fn sample_customer_order(
    plant_id: &str,
    market: &MarketDefinition,
    policy: &MarketBiddingPolicy,
    reputation_permille: u32,
    has_saw_on_floor: bool,
    has_inspection_on_floor: bool,
    order_seq: u64,
    now: SimTime,
    game_seed: u64,
) -> Option<CustomerOrder> {
    let win_permille = reference::reference_win_probability_permille(policy, reputation_permille);
    if win_permille == 0 {
        return None;
    }
    let mut rng = StreamRng::new(game_seed, "fsim-sales", &market.market_id, order_seq);
    if (rng.gen_range_i64(0, 999) as u32) >= win_permille {
        return None;
    }

    let base_payout = market.reference_payout_per_part.0;
    let scaled_payout = (base_payout * (policy.price_multiplier_pct as i64)) / 100;
    let jitter_pct = rng.gen_range_i64(90, 125);
    let payout = Money((scaled_payout * jitter_pct) / 100);
    if payout < policy.min_payout_per_hour {
        return None;
    }

    // In the tutorial or when no saw is installed yet, orders use precut blanks ("blank-alu").
    // When a saw is installed, some orders use raw bar ("raw-bar-alu") so the saw is exercised.
    let use_raw_bar = has_saw_on_floor && rng.gen_bool(0.5);
    let material_sku = if use_raw_bar {
        "raw-bar-alu".to_string()
    } else {
        "blank-alu".to_string()
    };

    let part_names = [
        "6061-T6 Sensor Mount Bracket",
        "7075 Actuator Housing",
        "Anodized Gimbal Yoke",
        "Precision Optical Baseplate",
        "Manifold Valve Block",
    ];
    let part_idx = (rng.gen_range_i64(0, (part_names.len() - 1) as i64)) as usize;

    Some(CustomerOrder {
        customer_order_id: format!("cust-{order_seq}"),
        plant_id: plant_id.to_string(),
        market_id: market.market_id.clone(),
        part_name: part_names[part_idx].to_string(),
        material_sku,
        requires_sawing: use_raw_bar,
        requires_inspection: has_inspection_on_floor || market.requires_cmm,
        quantity: 1,
        payout,
        created_at_ms: now.0,
        due_at_ms: now.add_ms(SimTime::DAY_MS * (policy.promised_lead_days.max(1) as i64)).0,
        status: "active".to_string(),
    })
}
